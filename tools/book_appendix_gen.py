#!/usr/bin/env python3
"""What the generators of the book's generated appendices share: tools/gen_appendix_c.py, gen_appendix_f.py and
gen_appendix_h.py. It is no command of its own.

A generator is a module with PAGE (the page it writes), SCRIPT (its own path), SOURCES (what the page's note says it
is written from) and `render(root)`, the page's whole text for the repository at `root`. `run` is its command line:

    python3 tools/gen_appendix_X.py            writes the page
    python3 tools/gen_appendix_X.py --check    writes nothing; exit 1, with the lines that differ, when the committed
                                               page is not what the generator would write

`stale` is the same comparison for tools/book_appendix_check.py, as the problems tools/book_check.py prints.

The page says that it is generated in a comment after its title (`with_note`). The comment cannot be the first thing
after the header: book/scripts/prepare.mjs takes the page's `# ` title off only where it starts the body.
"""
import argparse
import difflib
import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
INPUTS = "book/appendices"  # the hand-written inputs of the generators


class CannotWrite(Exception):
    """A source or an input no longer has the shape the generator reads: the page cannot be written."""


def need(condition, message):
    if not condition:
        raise CannotWrite(message)


def read(root, path):
    """A file of the repository as text, its line ends as they are."""
    try:
        with open(os.path.join(root, *path.split("/")), "rb") as f:
            return f.read().decode("utf-8")
    except (OSError, UnicodeDecodeError) as error:
        raise CannotWrite(f"{path} cannot be read ({error.__class__.__name__})")


def note(generator):
    return f"<!-- Generated by {generator.SCRIPT} from {generator.SOURCES}; edit those, not this page. -->"


def with_note(generator, page):
    """`page` with the generator's note after its title: the header stays the first thing in the file."""
    start = re.match(r"---\n.*?\n---\n\n# [^\n]*\n\n", page, re.S)
    need(start, f"the text of {generator.PAGE} does not start with a header, a blank line and its `# ` title")
    return page[:start.end()] + note(generator) + "\n\n" + page[start.end():]


def written(generator, root):
    """What the generator writes: the page with its note, or CannotWrite."""
    try:
        page = with_note(generator, generator.render(root))
    except CannotWrite:
        raise
    except (AssertionError, LookupError, ValueError, OSError) as error:
        # A generator's own consistency checks: an input row that names no page, a table cell with a `|` in it.
        raise CannotWrite(f"{error.__class__.__name__}: {error}")
    need("\r" not in page, "the text has a carriage return (an input has CRLF line ends)")
    return page


def command(generator):
    return f"python3 {generator.SCRIPT}"


def difference(generator, root):
    """None when the committed page is what the generator writes, else (a sentence, the lines that differ)."""
    try:
        mine = written(generator, root)
    except CannotWrite as error:
        return (f"{generator.SCRIPT} cannot write the page: {error}. Correct the source or the input it names, then"
                f" run `{command(generator)}`"), []
    try:
        theirs = read(root, generator.PAGE)
    except CannotWrite:
        return f"the page is not written: run `{command(generator)}`", []
    if mine == theirs:
        return None
    a, b = theirs.split("\n"), mine.split("\n")
    lines, changed, first = [], 0, None
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, a, b, autojunk=False).get_opcodes():
        if tag == "equal":
            continue
        changed += max(i2 - i1, j2 - j1)
        first = first if first is not None else i1 + 1
        old, new = a[i1:i2], b[j1:j2]
        if len(old) == len(new):  # show each pair of long lines from where the two part
            for k, (was, now) in enumerate(zip(old, new)):
                same = len(os.path.commonprefix([was, now]))
                if same > 60:
                    old[k], new[k] = "…" + was[same - 40:], "…" + now[same - 40:]
        lines += [f"  line {i1 + 1 + k}: - {line}" for k, line in enumerate(old)]
        lines += [f"  line {i1 + 1}: + {line}" for line in new]
    return (f"is not what {generator.SCRIPT} writes ({changed} {'line differs' if changed == 1 else 'lines differ'},"
            f" the first at line {first}): one of its sources changed ({generator.SOURCES}), or the page was edited by"
            f" hand. Run `{command(generator)}`; a change to the page's own text is made in the generator's inputs"), lines


def short(line, width=150):
    return line if len(line) <= width else line[:width - 1] + "…"


def stale(generator, root):
    """The problem of a page that is not what its generator writes, for tools/book_check.py: one line, or none."""
    found = difference(generator, root)
    if found is None:
        return []
    sentence, lines = found
    shown = f" ({short(lines[0].strip(), 110)})" if lines else ""
    return [f"{generator.PAGE}: {sentence}{shown}"]


def run(generator, doc):
    """The command line of a generator."""
    parser = argparse.ArgumentParser(description=doc.strip().splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="write nothing; exit 1 when the committed page is not what would be written")
    args = parser.parse_args()
    if args.check:
        found = difference(generator, ROOT)
        if found is None:
            print(f"{generator.PAGE}: up to date")
            return 0
        sentence, lines = found
        print(f"{generator.PAGE}: {sentence}.")
        for line in lines[:12]:
            print(short(line))
        if len(lines) > 12:
            print(f"  … and {len(lines) - 12} more")
        return 1
    try:
        page = written(generator, ROOT)
    except CannotWrite as error:
        print(f"{generator.SCRIPT}: {error}", file=sys.stderr)
        return 1
    with open(os.path.join(ROOT, *generator.PAGE.split("/")), "w", encoding="utf-8", newline="\n") as f:
        f.write(page)
    print(f"{generator.PAGE}: written ({page.count(chr(10))} lines)")
    return 0
