#!/usr/bin/env python3
"""Writes lib/std/checksum_tables.cee: the tables of lib/std's checksums and hashes (ADR 0075 §2.5).

- CRC32C_SLICES: CRC-32C (Castagnoli, polynomial 0x1EDC6F41, reflected 0x82F63B78), slicing-by-8.
- CRC64_NVME_SLICES: CRC-64/NVME (polynomial 0xAD93D23594C93659, reflected), slicing-by-8.
- MD5_SINES: MD5's 64 additive constants, floor(|sin(i + 1)| * 2^32) (RFC 1321 §3.4).
- SHA256_ROUNDS: SHA-256's 64 round constants, the first 32 bits of the fractional parts of the cube roots of the
  first 64 primes (FIPS 180-4 §4.2.2), computed with integer arithmetic.

Slice table k of a CRC is at [k * 256 .. k * 256 + 256]: table 0 is the byte-at-a-time table, and table k advances a
byte through k more zero bytes. A table is checked here against a bitwise CRC before it is written: a failure stops
the generator. The CRC model in tools/oracles/crc_model.py, which the tests use, is a separate implementation.

usage: python3 tools/gen_checksums.py   (formats with $CEESAFEC, default out/ceesafec)
"""

import math
import os
import subprocess

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))


def reflect(value, width):
    out = 0
    for _ in range(width):
        out = (out << 1) | (value & 1)
        value >>= 1
    return out


def slices(poly, width):
    rpoly = reflect(poly, width)
    t = [[0] * 256 for _ in range(8)]
    for i in range(256):
        c = i
        for _ in range(8):
            c = (c >> 1) ^ rpoly if c & 1 else c >> 1
        t[0][i] = c
    for k in range(1, 8):
        for i in range(256):
            t[k][i] = (t[k - 1][i] >> 8) ^ t[0][t[k - 1][i] & 0xFF]
    return [x for row in t for x in row], rpoly


def check(flat, rpoly, width, expected):
    """The slicing-by-8 tables over "123456789" against `expected`, and against a bitwise CRC of other inputs."""
    mask = (1 << width) - 1

    def bitwise(data):
        c = mask
        for b in data:
            c ^= b
            for _ in range(8):
                c = (c >> 1) ^ rpoly if c & 1 else c >> 1
        return c ^ mask

    def sliced(data):
        c = mask
        i = 0
        while i + 8 <= len(data):
            if width == 32:
                lo = c ^ int.from_bytes(data[i:i + 4], "little")
                hi = int.from_bytes(data[i + 4:i + 8], "little")
                word = lo | (hi << 32)
            else:
                word = c ^ int.from_bytes(data[i:i + 8], "little")
            c = 0
            for j in range(8):
                c ^= flat[(7 - j) * 256 + ((word >> (8 * j)) & 0xFF)]
            i += 8
        for b in data[i:]:
            c = flat[(c ^ b) & 0xFF] ^ (c >> 8)
        return c ^ mask

    assert bitwise(b"123456789") == expected, hex(bitwise(b"123456789"))
    for n in range(0, 40):
        data = bytes((k * 37 + n) & 0xFF for k in range(n))
        assert sliced(data) == bitwise(data), n


def md5_sines():
    return [int(abs(math.sin(i + 1)) * 2 ** 32) & 0xFFFFFFFF for i in range(64)]


def icbrt(n):
    """The integer cube root of n, floor(n ** (1/3))."""
    x = 1 << ((n.bit_length() + 2) // 3)
    while True:
        y = (2 * x + n // (x * x)) // 3
        if y >= x:
            break
        x = y
    while x * x * x > n:
        x -= 1
    while (x + 1) ** 3 <= n:
        x += 1
    return x


def sha256_rounds():
    primes = []
    n = 2
    while len(primes) < 64:
        if all(n % p for p in primes):
            primes.append(n)
        n += 1
    # floor(cbrt(p) * 2^32) mod 2^32 is the integer cube root of p * 2^96, mod 2^32
    return [icbrt(p << 96) & 0xFFFFFFFF for p in primes]


def table(name, kind, values, digits, per_line, doc):
    lines = [f"/// {doc}", f"static {name}: [{kind}; {len(values)}] = ["]
    for i in range(0, len(values), per_line):
        lines.append("    " + ", ".join(f"0x{v:0{digits}X}" for v in values[i:i + per_line]) + ",")
    lines.append("];")
    return "\n".join(lines)


def main():
    crc32c, r32 = slices(0x1EDC6F41, 32)
    check(crc32c, r32, 32, 0xE3069283)
    crc64, r64 = slices(0xAD93D23594C93659, 64)
    check(crc64, r64, 64, 0xAE8B14860A799888)
    sines = md5_sines()
    assert sines[0] == 0xD76AA478 and sines[63] == 0xEB86D391  # RFC 1321 §3.4: T[1] and T[64]
    rounds = sha256_rounds()
    assert rounds[0] == 0x428A2F98 and rounds[63] == 0xC67178F2  # FIPS 180-4 §4.2.2: K0 and K63
    source = "\n\n".join([
        "// GENERATED by tools/gen_checksums.py: edit that, not this file. The tables of lib/std/checksums.cee (ADR 0075\n"
        "// §2.5). Slice table k of a CRC is at [k * 256 .. k * 256 + 256].",
        table("CRC32C_SLICES", "u32", crc32c, 8, 8,
              "CRC-32C (Castagnoli, reflected 0x82F63B78), slicing-by-8: eight tables of 256."),
        table("CRC64_NVME_SLICES", "u64", crc64, 16, 4,
              "CRC-64/NVME (reflected 0x9A6C9329AC4BC9B5), slicing-by-8: eight tables of 256."),
        table("MD5_SINES", "u32", sines, 8, 8, "MD5's additive constants, floor(|sin(i + 1)| * 2^32) (RFC 1321 §3.4)."),
        table("SHA256_ROUNDS", "u32", rounds, 8, 8,
              "SHA-256's round constants: the cube roots of the first 64 primes (FIPS 180-4 §4.2.2)."),
    ]) + "\n"
    path = os.path.join(ROOT, "lib", "std", "checksum_tables.cee")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(source)
    formatter = os.environ.get("CEESAFEC", os.path.join(ROOT, "out", "ceesafec"))
    subprocess.run([formatter, "fmt", path], check=True)
    print(f"gen_checksums: wrote {path}")


if __name__ == "__main__":
    main()
