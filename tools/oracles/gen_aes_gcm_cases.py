#!/usr/bin/env python3
"""Writes tests/reference/tests/corpus/run-pass/aes-gcm.cee: lib/std's Aes256Gcm and ConstantTime.equal (ADR 0135)
against an oracle outside the code under test, tools/oracles/aes_gcm_model.py (AES-256-GCM from its definitions,
checked against the specification's test cases and, where the package is installed, against `cryptography`).

The program and this file build the same bytes (byte k of message(n, seed) is (k * 167 + seed * 13 + (k >> 7)) mod
256). Compiled, the program runs the CPU's instructions where the machine has them; interpreted, lib/std's own
constant-time code: both must print these lines. The cases:
1. test cases of the GCM specification (AES-256: 13 to 16);
2. for each pair of ROUNDS, associated data and a text of those lengths: `seal`'s tag and the SHA-256 of its
   ciphertext; `open` giving the text back; and one tampering, in turn a bit of the tag, of the ciphertext, of the
   associated data and of the nonce, refused with the buffer zeroed;
3. keys that are not 32 bytes; ConstantTime.equal.

The corpus program is short (two of the specification's cases, four rounds): the interpreter runs lib/std's
bit-sliced AES some thousand times slower than compiled code, and the corpus runs every program in it. The long list
(all four cases, every length around one, four and eight blocks, 4 KiB and 64 KiB) is tools/aes_gcm_check.py's,
which builds the same program from `program(…)` and runs it compiled only.

usage: python3 tools/oracles/gen_aes_gcm_cases.py   (formats with $CEESAFEC, default out/ceesafec)
"""

import hashlib
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from aes_gcm_model import seal, self_check  # noqa: E402

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))

# (associated data, text) lengths. The corpus's: few and short (see above).
ROUNDS = [(0, 0), (20, 1), (0, 17), (20, 129)]
CASES = ["tc15", "tc16"]
# tools/aes_gcm_check.py's: every length around one, four and eight blocks, then long ones.
LONG_ROUNDS = ([(a, n) for a in (0, 1, 20, 64, 257)
                for n in (0, 1, 15, 16, 17, 31, 32, 33, 63, 64, 65, 127, 128, 129, 255, 256, 257, 300, 1000)]
               + [(a, n) for a in (0, 20) for n in (4095, 4096, 65535, 65536, 65537)])
LONG_CASES = ["tc13", "tc14", "tc15", "tc16"]
KEY_LENGTHS = [0, 16, 31, 33, 64]


def message(n, seed):
    return bytes((k * 167 + seed * 13 + (k >> 7)) & 0xFF for k in range(n))


PROGRAM = '''// GENERATED by tools/oracles/gen_aes_gcm_cases.py: edit that, not this file.
// lib/std's Aes256Gcm and ConstantTime.equal (ADR 0135). Every expected line comes from an oracle outside the code
// under test: tools/oracles/aes_gcm_model.py, AES-256-GCM from its definitions. Compiled, this runs the CPU's
// instructions where the machine has them; interpreted, lib/std's constant-time code. tools/aes_gcm_check.py runs
// the same program with the long list of cases, compiled only.

fn message(n: usize, seed: usize) -> Vector<u8> {
    var v = Vector<u8>.create();
    for (k in 0..n) {
        v.push(truncate<u8>(k * 167 + seed * 13 + (k >> 7)))!;
    }
    return v;
}

fn writeHex(d: Slice<u8>) {
    let digits = "0123456789abcdef".bytes();
    var out = Vector<u8>.create();
    for (i in 0..d.length) {
        out.push(digits[(d[i] >> 4) as usize])!;
        out.push(digits[(d[i] & 15) as usize])!;
    }
    Console.write(StringView.fromUtf8(out.view()) ?? "?");
}

fn nonceOf(seed: usize) -> [u8; 12] {
    let m = message(12, seed);
    var n = [0u8; 12];
    for (i in 0..12) {
        n[i] = m[i];
    }
    return n;
}

fn sameBytes(a: Slice<u8>, b: Slice<u8>) -> bool {
    if (a.length != b.length) {
        return false;
    }
    for (i in 0..a.length) {
        if (a[i] != b[i]) {
            return false;
        }
    }
    return true;
}

fn allZero(a: Slice<u8>) -> bool {
    for (i in 0..a.length) {
        if (a[i] != 0) {
            return false;
        }
    }
    return true;
}

fn unhex(text: StringView) -> Vector<u8> {
    var out = Vector<u8>.create();
    let b = text.bytes();
    var i: usize = 0;
    while (i + 1 < b.length) {
        let high = if (b[i] >= 'a') b[i] - 'a' + 10 else b[i] - '0';
        let low = if (b[i + 1] >= 'a') b[i + 1] - 'a' + 10 else b[i + 1] - '0';
        out.push((high << 4) | low)!;
        i += 2;
    }
    return out;
}

/// One test case of the GCM specification: the tag and the ciphertext `seal` gives.
fn specification(name: StringView, key: StringView, nonce: StringView, text: StringView, aad: StringView) {
    let cipher = match (Aes256Gcm.create(unhex(key).view())) {
        Some(c) => c,
        null => { return; }
    };
    let n = unhex(nonce);
    var iv = [0u8; 12];
    for (i in 0..12) {
        iv[i] = n[i];
    }
    var data = unhex(text);
    let tag = cipher.seal(iv, unhex(aad).view(), data.viewMut());
    Console.write(name);
    Console.write(" ");
    writeHex(tag[..]);
    if (data.length > 0) {
        Console.write(" ");
        writeHex(data.view());
    }
    Console.writeLine("");
}

/// Seals message(n, …) with associated data of `a` bytes, opens it again, and tampers with one thing.
fn round(a: usize, n: usize, seed: usize) {
    let cipher = match (Aes256Gcm.create(message(32, seed).view())) {
        Some(c) => c,
        null => { return; }
    };
    let nonce = nonceOf(seed + 100);
    var aad = message(a, seed + 200);
    let text = message(n, seed + 300);
    var data = message(n, seed + 300);
    let tag = cipher.seal(nonce, aad.view(), data.viewMut());
    Console.write("seal ");
    Console.write(a);
    Console.write(" ");
    Console.write(n);
    Console.write(" ");
    writeHex(tag[..]);
    Console.write(" ");
    let digest = Sha256.of(data.view());
    writeHex(digest[..]);
    Console.writeLine("");
    var sealed = Vector<u8>.create();
    sealed.extend(data.view())!;
    let opened = cipher.open(nonce, aad.view(), data.viewMut(), tag) && sameBytes(data.view(), text.view());
    Console.writeLine(if (opened) "open ok" else "open FAILED");
    // One thing changed by a bit, in turn: the tag, the ciphertext, the associated data, the nonce.
    var badTag = tag;
    var badNonce = nonce;
    var what = seed % 4;
    if (what == 1 && n == 0) {
        what = 0;
    }
    if (what == 2 && a == 0) {
        what = 3;
    }
    if (what == 0) {
        badTag[seed % 16] = badTag[seed % 16] ^ 1;
    } else if (what == 1) {
        sealed[seed % n] = sealed[seed % n] ^ 0x80;
    } else if (what == 2) {
        aad[seed % a] = aad[seed % a] ^ 4;
    } else {
        badNonce[seed % 12] = badNonce[seed % 12] ^ 2;
    }
    let accepted = cipher.open(badNonce, aad.view(), sealed.viewMut(), badTag);
    Console.writeLine(if (!accepted && allZero(sealed.view())) "tamper refused" else "tamper ACCEPTED");
}

fn main() {
SPECIFICATION_CALLS
    let aads: [usize; ROUND_COUNT] = [AAD_LIST];
    let lengths: [usize; ROUND_COUNT] = [LENGTH_LIST];
    for (i in 0..aads.length) {
        round(aads[i], lengths[i], i + 1);
    }
    let keys: [usize; KEY_COUNT] = [KEY_LIST];
    for (i in 0..keys.length) {
        Console.write("key ");
        Console.write(keys[i]);
        Console.writeLine(if (Aes256Gcm.create(message(keys[i], 9).view()).isNull()) " refused" else " ACCEPTED");
    }
    let one = message(40, 1);
    var other = message(40, 1);
    Console.writeLine(if (ConstantTime.equal(one.view(), other.view())) "equal same" else "equal WRONG");
    other[39] = other[39] ^ 1;
    Console.writeLine(if (!ConstantTime.equal(one.view(), other.view())) "equal last byte" else "equal WRONG");
    other[39] = other[39] ^ 1;
    other[0] = other[0] ^ 0x80;
    Console.writeLine(if (!ConstantTime.equal(one.view(), other.view())) "equal first byte" else "equal WRONG");
    Console.writeLine(if (!ConstantTime.equal(one.view(), one.view()[0..39])) "equal lengths" else "equal WRONG");
    Console.writeLine(if (ConstantTime.equal("".bytes(), "".bytes())) "equal empty" else "equal WRONG");
}
'''


ZERO_KEY = bytes(32)
KEY = bytes.fromhex("feffe9928665731c6d6a8f9467308308feffe9928665731c6d6a8f9467308308")
NONCE = bytes.fromhex("cafebabefacedbaddecaf888")
TEXT = bytes.fromhex(
    "d9313225f88406e5a55909c5aff5269a86a7a9531534f7da2e4c303d8a318a72"
    "1c3c0c95956809532fcf0e2449a6b525b16aedf5aa0de657ba637b391aafd255")
AAD = bytes.fromhex("feedfacedeadbeeffeedfacedeadbeefabaddad2")
SPECIFICATION = {
    "tc13": (ZERO_KEY, bytes(12), b"", b""),
    "tc14": (ZERO_KEY, bytes(12), bytes(16), b""),
    "tc15": (KEY, NONCE, TEXT, b""),
    "tc16": (KEY, NONCE, TEXT[:60], AAD),
}


def program(cases, rounds):
    """The program's source (not formatted) and the lines it must print."""
    lines = []
    calls = []
    for name in cases:
        k, n, p, a = SPECIFICATION[name]
        c, t = seal(k, n, a, p)
        lines.append(("%s %s %s" % (name, t.hex(), c.hex())).rstrip())
        calls.append('    specification("%s", "%s", "%s", "%s", "%s");\n' % (name, k.hex(), n.hex(), p.hex(), a.hex()))
    seed = 0
    for a, n in rounds:
        seed += 1
        c, t = seal(message(32, seed), message(12, seed + 100), message(a, seed + 200), message(n, seed + 300))
        lines.append("seal %d %d %s %s" % (a, n, t.hex(), hashlib.sha256(c).hexdigest()))
        lines.append("open ok")
        lines.append("tamper refused")
    for k in KEY_LENGTHS:
        lines.append("key %d refused" % k)
    lines += ["equal same", "equal last byte", "equal first byte", "equal lengths", "equal empty"]
    source = (PROGRAM.replace("SPECIFICATION_CALLS\n", "".join(calls))
              .replace("ROUND_COUNT", str(len(rounds)))
              .replace("AAD_LIST", ", ".join(str(a) for a, _ in rounds))
              .replace("LENGTH_LIST", ", ".join(str(n) for _, n in rounds))
              .replace("KEY_COUNT", str(len(KEY_LENGTHS))).replace("KEY_LIST", ", ".join(str(n) for n in KEY_LENGTHS)))
    return source, lines


def main():
    print("gen_aes_gcm_cases: the model:", self_check())
    source, lines = program(CASES, ROUNDS)
    source = source + "\n" + "".join(f"// expect-stdout: {line}\n" for line in lines)
    path = os.path.join(ROOT, "tests", "reference", "tests", "corpus", "run-pass", "aes-gcm.cee")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(source)
    ceesafec = os.environ.get("CEESAFEC", os.path.join(ROOT, "out", "ceesafec"))
    subprocess.run([ceesafec, "fmt", path], check=True)
    print(f"gen_aes_gcm_cases: wrote {path} ({len(lines)} expected lines)")


if __name__ == "__main__":
    main()
