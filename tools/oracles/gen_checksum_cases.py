#!/usr/bin/env python3
"""Writes tests/reference/tests/corpus/run-pass/checksums.cee: lib/std's Crc32c, Crc64Nvme, Md5, Sha256 and HmacSha256
(ADR 0075 §2.5) against oracles outside the code under test.

- MD5, SHA-256 and HMAC-SHA-256: Python's hashlib and hmac.
- CRC-32C and CRC-64/NVME: tools/oracles/crc_model.py, a bitwise model checked against the catalogued check values.

The program and this file build the same messages (byte k of message(n, seed) is (k * 167 + seed * 13 + (k >> 7))
mod 256). The cases:
1. the check string "123456789", under each algorithm;
2. message(n, 1) for lengths around every block boundary (0, 1, 55, 56, 57, 63, 64, 65, 119, 120, ... and longer);
3. (the million-byte "a" message is left out: the interpreter's corpus run would time out);
4. message(130, 2) fed as two updates split at every offset 0..130, under each algorithm (HMAC keyed by
   message(20, 3)); then message(1000, 4) fed one byte at a time, and message(5000, 5) in chunks of 1, 2, 3, ...;
5. finish then more bytes: finish is taken after message(70, 6)'s first 33 bytes, and again after the rest;
6. HMAC-SHA-256 with keys shorter than, equal to and longer than the 64-byte block, on several message lengths.

usage: python3 tools/oracles/gen_checksum_cases.py   (formats with $CEESAFEC, default out/ceesafec)
"""

import hashlib
import hmac
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from crc_model import crc32c, crc64nvme, self_check  # noqa: E402

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))

LENGTHS = [0, 1, 2, 3, 7, 8, 9, 15, 16, 17, 31, 32, 33, 55, 56, 57, 63, 64, 65, 100, 119, 120, 121, 127, 128, 129,
           1000, 4096, 8193]
HMAC_KEYS = [0, 1, 20, 32, 63, 64, 65, 100, 131, 200]
HMAC_MESSAGES = [0, 1, 55, 64, 200]


def message(n, seed):
    return bytes((k * 167 + seed * 13 + (k >> 7)) & 0xFF for k in range(n))


def all_five(data, key):
    return "%d %d %s %s %s" % (crc32c(data), crc64nvme(data), hashlib.md5(data).hexdigest(),
                               hashlib.sha256(data).hexdigest(), hmac.new(key, data, "sha256").hexdigest())


PROGRAM = '''// GENERATED by tools/oracles/gen_checksum_cases.py: edit that, not this file.
// lib/std's Crc32c, Crc64Nvme, Md5, Sha256 and HmacSha256 (ADR 0075 §2.5). Every expected line comes from oracles
// outside the code under test: Python's hashlib and hmac, and the bitwise CRC model in tools/oracles/crc_model.py.

fn message(n: usize, seed: usize) -> Vector<u8> {
    var v = Vector<u8>.create();
    for (k in 0..n) {
        v.push(truncate<u8>(k * 167 + seed * 13 + (k >> 7)))!;
    }
    return v;
}

fn writeHex(d: Slice<u8>) {
    let digits = "0123456789abcdef".bytes();
    var out = Vector<u8>.create();
    for (b in d) {
        out.push(digits[(b >> 4) as usize])!;
        out.push(digits[(b & 15) as usize])!;
    }
    Console.write(StringView.fromUtf8(out[..]) ?? "?");
}

/// The five checksums of `data`, on one line after `label`; HMAC keyed by `key`.
fn showAll(label: StringView, n: usize, data: Slice<u8>, key: Slice<u8>) {
    Console.write(label);
    Console.write(" ");
    Console.write(n);
    Console.write(" ");
    Console.write(Crc32c.of(data));
    Console.write(" ");
    Console.write(Crc64Nvme.of(data));
    Console.write(" ");
    let m = Md5.of(data);
    writeHex(m[..]);
    Console.write(" ");
    let s = Sha256.of(data);
    writeHex(s[..]);
    Console.write(" ");
    let h = HmacSha256.of(key, data);
    writeHex(h[..]);
    Console.writeLine("");
}

/// Five states fed the same updates.
struct Five {
    crc32c: Crc32c;
    crc64: Crc64Nvme;
    md5: Md5;
    sha256: Sha256;
    hmac: HmacSha256;

    fn create(key: Slice<u8>) -> Five => Five {
        crc32c: Crc32c.create(),
        crc64: Crc64Nvme.create(),
        md5: Md5.create(),
        sha256: Sha256.create(),
        hmac: HmacSha256.create(key),
    };

    fn feed(borrow mut this, bytes: Slice<u8>) {
        this.crc32c.update(bytes);
        this.crc64.update(bytes);
        this.md5.update(bytes);
        this.sha256.update(bytes);
        this.hmac.update(bytes);
    }

    fn show(borrow this, label: StringView, n: usize) {
        Console.write(label);
        Console.write(" ");
        Console.write(n);
        Console.write(" ");
        Console.write(this.crc32c.finish());
        Console.write(" ");
        Console.write(this.crc64.finish());
        Console.write(" ");
        let m = this.md5.finish();
        writeHex(m[..]);
        Console.write(" ");
        let s = this.sha256.finish();
        writeHex(s[..]);
        Console.write(" ");
        let h = this.hmac.finish();
        writeHex(h[..]);
        Console.writeLine("");
    }
}

fn main() {
    let empty = Vector<u8>.create();
    let check = "123456789";
    let key = message(20, 3);
    showAll("check", 9, check.bytes(), key[..]);
    let lengths: [usize; LENGTH_COUNT] = [LENGTH_LIST];
    for (n in lengths) {
        let m = message(n, 1);
        showAll("length", n, m[..], key[..]);
    }
    let split = message(130, 2);
    for (p in 0..131usize) {
        var f = Five.create(key[..]);
        f.feed(split[..p]);
        f.feed(split[p..]);
        f.show("split", p);
    }
    let bytewise = message(1000, 4);
    var one = Five.create(key[..]);
    for (k in 0..bytewise.length) {
        one.feed(bytewise[k..k + 1]);
    }
    one.show("bytewise", 1000);
    let chunked = message(5000, 5);
    var chunks = Five.create(key[..]);
    var at: usize = 0;
    var size: usize = 1;
    while (at < chunked.length) {
        let end = if (at + size < chunked.length) at + size else chunked.length;
        chunks.feed(chunked[at..end]);
        at = end;
        size += 1;
    }
    chunks.show("chunked", 5000);
    let more = message(70, 6);
    var going = Five.create(key[..]);
    going.feed(more[..33]);
    going.show("finish", 33);
    going.feed(more[33..]);
    going.show("finish", 70);

    let keyLengths: [usize; KEY_COUNT] = [KEY_LIST];
    let messageLengths: [usize; MESSAGE_COUNT] = [MESSAGE_LIST];
    for (k in keyLengths) {
        let hmacKey = message(k, 7);
        for (n in messageLengths) {
            let m = message(n, 8);
            let code = HmacSha256.of(hmacKey[..], m[..]);
            Console.write("hmac ");
            Console.write(k);
            Console.write(" ");
            Console.write(n);
            Console.write(" ");
            writeHex(code[..]);
            Console.writeLine("");
        }
    }
    let none = HmacSha256.of(empty[..], empty[..]);
    Console.write("hmac-empty ");
    writeHex(none[..]);
    Console.writeLine("");
}
'''


def main():
    self_check()
    key = message(20, 3)
    lines = ["check 9 " + all_five(b"123456789", key)]
    for n in LENGTHS:
        lines.append("length %d %s" % (n, all_five(message(n, 1), key)))
    split = message(130, 2)
    for p in range(131):
        lines.append("split %d %s" % (p, all_five(split, key)))
    lines.append("bytewise 1000 " + all_five(message(1000, 4), key))
    lines.append("chunked 5000 " + all_five(message(5000, 5), key))
    more = message(70, 6)
    lines.append("finish 33 " + all_five(more[:33], key))
    lines.append("finish 70 " + all_five(more, key))
    for k in HMAC_KEYS:
        for n in HMAC_MESSAGES:
            lines.append("hmac %d %d %s" % (k, n, hmac.new(message(k, 7), message(n, 8), "sha256").hexdigest()))
    lines.append("hmac-empty " + hmac.new(b"", b"", "sha256").hexdigest())
    program = (PROGRAM.replace("LENGTH_COUNT", str(len(LENGTHS)))
               .replace("LENGTH_LIST", ", ".join(str(n) for n in LENGTHS))
               .replace("KEY_COUNT", str(len(HMAC_KEYS)))
               .replace("KEY_LIST", ", ".join(str(n) for n in HMAC_KEYS))
               .replace("MESSAGE_COUNT", str(len(HMAC_MESSAGES)))
               .replace("MESSAGE_LIST", ", ".join(str(n) for n in HMAC_MESSAGES)))
    source = program + "\n" + "".join(f"// expect-stdout: {line}\n" for line in lines)
    path = os.path.join(ROOT, "tests", "reference", "tests", "corpus", "run-pass", "checksums.cee")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(source)
    ceesafec = os.environ.get("CEESAFEC", os.path.join(ROOT, "out", "ceesafec"))
    subprocess.run([ceesafec, "fmt", path], check=True)
    print(f"gen_checksum_cases: wrote {path} ({len(lines)} expected lines)")


if __name__ == "__main__":
    main()
