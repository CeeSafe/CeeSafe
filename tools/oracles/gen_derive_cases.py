#!/usr/bin/env python3
"""Writes tests/reference/tests/corpus/run-pass/derive-keys.cee: `@derive(Equal, HashKey, OrderKey)` (ADR 0087 §2.3)
against oracles in this file.

1. A struct key (a group byte, then a name) and an enum key (Small(u32), Big(u32, u32), None) are put into lib/std's
   OrderedMap in a seeded random order, duplicates included; the map's iteration order must be Python's sort of the
   same keys as tuples: fields in declaration order, an enum's variant index first, strings bytewise.
2. The same struct keys in a HashMap: each distinct key counted, every lookup's answer from a Python dict, and the
   iteration order a model of ADR 0052 §2's (insertion order; no removals here).

usage: python3 tools/oracles/gen_derive_cases.py   (formats with $CEESAFEC, default out/ceesafec)
"""

import os
import random
import subprocess

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "tests", "reference", "tests", "corpus", "run-pass", "derive-keys.cee")
NAMES = ["ab", "a", "b", "", "ba", "abc", "z"]


def main():
    rng = random.Random(87)
    structs = [(rng.randrange(0, 4), rng.choice(NAMES)) for _ in range(40)]
    enums = []
    for _ in range(30):
        kind = rng.randrange(0, 3)
        if kind == 0:
            enums.append((0, rng.randrange(0, 5)))
        elif kind == 1:
            enums.append((1, rng.randrange(0, 3), rng.randrange(0, 3)))
        else:
            enums.append((2,))
    probes = [(rng.randrange(0, 5), rng.choice(NAMES + ["q"])) for _ in range(20)]

    def struct_literal(k):
        return f"key({k[0]}, \"{k[1]}\")"

    def enum_literal(k):
        if k[0] == 0:
            return f"Kind.Small({k[1]})"
        if k[0] == 1:
            return f"Kind.Big({k[1]}, {k[2]})"
        return "Kind.None"

    def enum_text(k):
        if k[0] == 0:
            return f"small {k[1]}"
        if k[0] == 1:
            return f"big {k[1]} {k[2]}"
        return "none"

    lines = []
    body = []
    body.append("    var ordered = OrderedMap<Key, u32>.create();")
    for k in structs:
        body.append(f"    ordered.put({struct_literal(k)}, 0)!;")
    body.append("    showKeys(ordered);")
    for k in sorted(set((g, n.encode()) for g, n in structs)):
        lines.append(f"{k[0]} '{k[1].decode()}'")
    body.append("    var kinds = OrderedMap<Kind, u32>.create();")
    for k in enums:
        body.append(f"    kinds.put({enum_literal(k)}, 0)!;")
    body.append("    showKinds(kinds);")
    for k in sorted(set(enums)):
        lines.append(enum_text(k))
    body.append("    var counts = HashMap<Key, u32>.create();")
    order, count = [], {}
    for k in structs:
        body.append(f"    bump(mut counts, {struct_literal(k)});")
        if k not in count:
            order.append(k)
            count[k] = 0
        count[k] += 1
    for k in probes:
        body.append(f"    probe(counts, {struct_literal(k)});")
        lines.append(f"{count[k]}" if k in count else "absent")
    body.append("    showCounts(counts);")
    for k in order:
        lines.append(f"{k[0]} '{k[1]}' {count[k]}")

    source = f"""// GENERATED by tools/oracles/gen_derive_cases.py: edit that, not this file.
// `@derive(Equal, HashKey, OrderKey)` (ADR 0087 §2.3) against the generator's oracles: an OrderedMap of derived keys
// iterates in Python's tuple order (fields in declaration order, an enum's variant index first, strings bytewise),
// and a HashMap of them finds what a Python dict finds, in insertion order.
@derive(Equal, HashKey, OrderKey)
struct Key {{
    group: u8;
    name: String;
}}

@derive(Equal, HashKey, OrderKey)
enum Kind {{
    Small(u32),
    Big(u32, u32),
    None,
}}

fn key(group: u8, name: StringView) -> Key {{
    var text = String.create();
    text.append(name)!;
    return Key {{ group: group, name: text }};
}}

fn showKeys(map: borrow OrderedMap<Key, u32>) {{
    var at = map.first();
    while (at != null) {{
        let k = map.keyAt(at!);
        var line = String.create();
        line.appendNumber(k.group)!;
        line.append(" '")!;
        line.append(k.name.view())!;
        line.append("'")!;
        Console.writeLine(line.view());
        at = map.next(at!);
    }}
}}

fn showKinds(map: borrow OrderedMap<Kind, u32>) {{
    var at = map.first();
    while (at != null) {{
        var line = String.create();
        match (map.keyAt(at!)) {{
            Kind.Small(n) => {{
                line.append("small ")!;
                line.appendNumber(n)!;
            }}
            Kind.Big(a, b) => {{
                line.append("big ")!;
                line.appendNumber(a)!;
                line.append(" ")!;
                line.appendNumber(b)!;
            }}
            Kind.None => {{ line.append("none")!; }}
        }}
        Console.writeLine(line.view());
        at = map.next(at!);
    }}
}}

fn bump(counts: borrow mut HashMap<Key, u32>, k: Key) {{
    let n = match (counts.get(k)) {{
        Some(v) => v + 1,
        null => 1,
    }};
    counts.put(k, n)!;
}}

fn probe(counts: borrow HashMap<Key, u32>, k: Key) {{
    match (counts.get(k)) {{
        Some(v) => {{ Console.writeLine(v); }}
        null => {{ Console.writeLine("absent"); }}
    }}
}}

fn showCounts(counts: borrow HashMap<Key, u32>) {{
    for (i in 0..counts.length()) {{
        let k = counts.keyAt(i);
        var line = String.create();
        line.appendNumber(k.group)!;
        line.append(" '")!;
        line.append(k.name.view())!;
        line.append("' ")!;
        line.appendNumber(counts.valueAt(i))!;
        Console.writeLine(line.view());
    }}
}}

fn main() {{
{chr(10).join(body)}
}}
""" + "".join(f"// expect-stdout: {line}\n" for line in lines)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(source)
    formatter = os.environ.get("CEESAFEC", os.path.join(ROOT, "out", "ceesafec"))
    subprocess.run([formatter, "fmt", OUT], check=True)
    print(f"gen_derive_cases: wrote {OUT} ({len(lines)} expected lines)")


if __name__ == "__main__":
    main()
