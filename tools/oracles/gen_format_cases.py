#!/usr/bin/env python3
"""Writes tests/reference/tests/corpus/run-pass/format-helpers.cee: lib/core's formatting helpers (ADR 0087 §2.9),
`appendHex`, `appendOctal`, `appendFixed` and `appendPadded` on a `String` and through `VectorBytes`, against
Python's `format`, whose `x`, `X`, `o`, `.Nf` and `<`/`>`/`^` specifiers write what Rust's do: `.Nf` rounds the exact
binary value half to even.

Cases: fixed integers and seeded random u64s in hex (widths 0, 4, 16, both cases) and octal; floats chosen to sit on
ties (0.125, 2.5, 0.5, 1e-7, …), negative zero, large and tiny magnitudes and seeded random doubles at 0 to 20
digits; texts with multibyte characters padded left, right and centre with ASCII and non-ASCII fills.

usage: python3 tools/oracles/gen_format_cases.py   (formats with $CEESAFEC, default out/ceesafec)
"""

import math
import os
import random
import struct
import subprocess

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "tests", "reference", "tests", "corpus", "run-pass", "format-helpers.cee")


def float_literal(x):
    """A CeeSafe expression for the double `x`, exact: its bits."""
    bits = struct.unpack("<Q", struct.pack("<d", x))[0]
    return f"f64.fromBits(0x{bits:016X})"


def fixed(x, digits):
    if math.isnan(x):
        return "NaN"
    if math.isinf(x):
        return "-inf" if x < 0 else "inf"
    return format(x, f".{digits}f")


def main():
    rng = random.Random(2987)
    body, lines = [], []

    integers = [0, 1, 7, 8, 15, 16, 255, 256, 4095, 0xDEADBEEF, (1 << 64) - 1]
    integers += [rng.getrandbits(64) for _ in range(8)]
    for n in integers:
        for width, upper in ((0, False), (4, True), (16, False)):
            body.append(f"    hex({n}, {width}, {'true' if upper else 'false'});")
            spec = f"0{width}{'X' if upper else 'x'}" if width else ("X" if upper else "x")
            lines.append(format(n, spec))
        body.append(f"    octal({n});")
        lines.append(format(n, "o"))

    floats = [0.0, -0.0, 0.125, 0.375, 2.5, 3.5, 0.5, 1.5, -2.5, 1e-7, 123456.789, 1e21, 5e-324, 1.7976931348623157e308,
              0.1, 0.7, 9.995, 99.5, float("nan"), float("inf"), float("-inf")]
    floats += [struct.unpack("<d", struct.pack("<Q", rng.getrandbits(62)))[0] for _ in range(2)]
    floats += [rng.uniform(-1000, 1000) for _ in range(6)]
    for x in floats:
        for digits in (0, 1, 2, 3, 6, 20):
            if abs(x) > 1e30 and digits == 20:
                continue
            body.append(f"    fixed({float_literal(x)}, {digits});")
            lines.append(fixed(x, digits))

    texts = ["", "ab", "héllo", "日本", "exactly8"]
    aligns = (("Left", "<"), ("Right", ">"), ("Center", "^"))
    fills = ((ord(" "), " "), (ord("*"), "*"), (0x2500, "─"))
    for text in texts:
        for width in (0, 3, 8):
            for name, mark in aligns:
                for code, char in fills[:2] if width != 8 else fills:
                    body.append(f"    padded(\"{text}\", {width}, TextAlign.{name}, {code});")
                    lines.append("[" + format(text, f"{char}{mark}{width}") + "]")

    source = f"""// GENERATED by tools/oracles/gen_format_cases.py: edit that, not this file.
// lib/core's formatting helpers (ADR 0087 §2.9) against Python's `format`: `appendHex`, `appendOctal`, `appendFixed`
// and `appendPadded` on a `String`, each line checked against the same helper through `VectorBytes` on a byte vector.

fn same(text: borrow String, bytes: borrow Vector<u8>) {{
    assert(text.view().bytes() == bytes.view(), "String and VectorBytes differ");
    Console.writeLine(text.view());
}}

fn hex(value: u64, width: u32, upper: bool) {{
    var s = String.create();
    s.appendHex(value, width, upper)!;
    var v = Vector<u8>.create();
    VectorBytes.appendHex(mut v, value, width, upper)!;
    same(s, v);
}}

fn octal(value: u64) {{
    var s = String.create();
    s.appendOctal(value)!;
    var v = Vector<u8>.create();
    VectorBytes.appendOctal(mut v, value)!;
    same(s, v);
}}

fn fixed(value: f64, digits: u32) {{
    var s = String.create();
    s.appendFixed(value, digits)!;
    var v = Vector<u8>.create();
    VectorBytes.appendFixed(mut v, value, digits)!;
    same(s, v);
}}

fn padded(text: StringView, width: usize, align: TextAlign, fill: u32) {{
    var s = String.create();
    s.append("[")!;
    s.appendPadded(text, width, align, fill)!;
    s.append("]")!;
    var v = Vector<u8>.create();
    v.push('[')!;
    VectorBytes.appendPadded(mut v, text, width, align, fill)!;
    v.push(']')!;
    same(s, v);
}}

fn main() {{
{chr(10).join(body)}
}}
""" + "".join(f"// expect-stdout: {line}\n" for line in lines)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(source)
    formatter = os.environ.get("CEESAFEC", os.path.join(ROOT, "out", "ceesafec"))
    subprocess.run([formatter, "fmt", OUT], check=True)
    print(f"gen_format_cases: wrote {OUT} ({len(lines)} expected lines)")


if __name__ == "__main__":
    main()
