#!/usr/bin/env python3
"""Writes tests/reference/tests/corpus/run-pass/int-conversions.cee: checkedTruncate<T> and saturatingTruncate<T> of
an integer (ADR 0074 §2.9) for every pair of integer types, at the bounds, with each expected line from Python's
unbounded integers, the oracle: `checkedTruncate<T>(v)` is v when T's least <= v <= T's greatest, else null;
`saturatingTruncate<T>(v)` is v, or the nearer bound. `isize` and `usize` are 64 bits, as the compiler's types are.

usage: python3 tools/oracles/gen_int_conversion_cases.py   (formats with $CEESAFEC, default out/ceesafec)
"""

import os
import subprocess

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))

TYPES = [
    ("i8", True, 8), ("i16", True, 16), ("i32", True, 32), ("i64", True, 64), ("isize", True, 64),
    ("u8", False, 8), ("u16", False, 16), ("u32", False, 32), ("u64", False, 64), ("usize", False, 64),
]


def bounds(signed, bits):
    return (-(1 << (bits - 1)), (1 << (bits - 1)) - 1) if signed else (0, (1 << bits) - 1)


def values_for(source, target):
    """The source values that test the pair: the source's bounds, the target's bounds and their neighbours, -1, 0, 1."""
    low, high = bounds(source[1], source[2])
    t_low, t_high = bounds(target[1], target[2])
    candidates = {low, low + 1, high - 1, high, -1, 0, 1, t_low - 1, t_low, t_low + 1, t_high - 1, t_high, t_high + 1}
    return sorted(v for v in candidates if low <= v <= high)


def expected(target, v):
    t_low, t_high = bounds(target[1], target[2])
    checked = str(v) if t_low <= v <= t_high else "null"
    saturated = min(max(v, t_low), t_high)
    return f"{checked} {saturated}"


def function_name(source, target):
    return source[0] + "To" + target[0][0].upper() + target[0][1:]


def main():
    lines = [
        "// GENERATED by tools/oracles/gen_int_conversion_cases.py: edit that, not this file.",
        "// checkedTruncate<T> and saturatingTruncate<T> of an integer (ADR 0074 §2.9), for every pair of integer types at",
        "// the bounds; each expected line is from Python's unbounded integers.",
    ]
    expectations = []
    calls = []
    for source in TYPES:
        for target in TYPES:
            name = function_name(source, target)
            values = values_for(source, target)
            literals = ", ".join(str(v) for v in values)
            lines.append(f"fn {name}() {{")
            lines.append(f"    let values: [{source[0]}; {len(values)}] = [{literals}];")
            lines.append("    for (v in values) {")
            lines.append(f'        Console.write("{source[0]}->{target[0]} ");')
            lines.append("        Console.write(v);")
            lines.append('        Console.write(" ");')
            lines.append(f"        match (checkedTruncate<{target[0]}>(v)) {{")
            lines.append("            Some(x) => { Console.write(x); }")
            lines.append('            null => { Console.write("null"); }')
            lines.append("        }")
            lines.append('        Console.write(" ");')
            lines.append(f"        Console.writeLine(saturatingTruncate<{target[0]}>(v));")
            lines.append("    }")
            lines.append("}")
            calls.append(f"    {name}();")
            for v in values:
                expectations.append(f"// expect-stdout: {source[0]}->{target[0]} {v} {expected(target, v)}")
    lines.append("fn main() {")
    lines.extend(calls)
    lines.append("}")
    lines.extend(expectations)
    path = os.path.join(ROOT, "tests", "reference", "tests", "corpus", "run-pass", "int-conversions.cee")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    ceesafec = os.environ.get("CEESAFEC", os.path.join(ROOT, "out", "ceesafec"))
    subprocess.run([ceesafec, "fmt", path], check=True)


if __name__ == "__main__":
    main()
