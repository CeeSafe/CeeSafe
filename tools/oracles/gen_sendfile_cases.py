#!/usr/bin/env python3
"""Writes tests/reference/tests/corpus/run-pass/async-send-file.cee: lib/std's sendFile and sendFileAll (ADR 0051) on
one file, with each expected line computed here, the oracle.

The program writes the file itself in a fresh temporary directory: SIZE bytes, byte i being (7 * i + 3) % 251, the
same rule as content() below. Each case sends a range of it to a peer that reads slowly through small socket buffers
(so sends are partial), until the sender shuts its side down; the line is "<result> <bytes the peer read> <their
FNV-1a 32>", where the result is "ok" or the IoError's name. Then:

- one sendFile step of the whole file: "1" if it sent between 1 and SIZE bytes and the peer read exactly those;
- one sendFile step at the file's end: its count, 0;
- the whole file on two streams at once: both lines must be the whole file's;
- the file's own position afterwards: a plain read still starts at byte 0 (its first five bytes).

usage: python3 tools/oracles/gen_sendfile_cases.py   (formats with $CEESAFEC, default out/ceesafec)
"""

import os
import subprocess

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))
SIZE = 100001

# (offset, length) sent with sendFileAll.
RANGES = [
    (0, 0),
    (0, 1),
    (0, SIZE),
    (40961, 30000),
    (SIZE - 1, 1),
    (SIZE - 10, 20),   # past the end: InvalidInput, the last ten bytes sent
    (SIZE, 5),         # at the end: InvalidInput, nothing sent
]


def content():
    return bytes((7 * i + 3) % 251 for i in range(SIZE))


def fnv(data):
    h = 2166136261
    for b in data:
        h = ((h ^ b) * 16777619) & 0xFFFFFFFF
    return h


def main():
    data = content()
    expected = []
    for offset, length in RANGES:
        sent = data[offset:offset + length]
        result = "ok" if offset + length <= SIZE else "InvalidInput"
        expected.append(f"{result} {len(sent)} {fnv(sent)}")
    expected.append("1")
    expected.append("0")
    expected += [f"ok {SIZE} {fnv(data)}"] * 2
    expected.append("position " + " ".join(str(b) for b in data[:5]))

    calls = "\n".join(
        f"    out[{2 * k}] = await line(borrow listener, port, file, {offset}, {length}, mut out[{2 * k + 1}])?;"
        for k, (offset, length) in enumerate(RANGES)
    )
    n = len(RANGES)
    source = f"""// GENERATED by tools/oracles/gen_sendfile_cases.py: edit that, not this file.
// lib/std's sendFile and sendFileAll (ADR 0051): ranges of one file sent to a slow reader through small socket buffers,
// one step, a step at the end, the file on two streams at once, and the file's own position left alone. Each expected
// line is the generator's (the bytes' count and FNV-1a, computed in Python).

fn io<T>(r: Result<T, IoError>) -> Result<T, AsyncError> => match (r) {{
    Ok(v) => Ok(v),
    Err(e) => Err(AsyncError.Io(e)),
}};

fn done(r: Result<void, IoError>) -> Result<void, AsyncError> => match (r) {{
    Ok() => Ok(),
    Err(e) => Err(AsyncError.Io(e)),
}};

fn fnv(h: u32, bytes: Slice<u8>) -> u32 {{
    var x = h;
    for (b in bytes) {{
        x = truncate<u32>((x ^ (b as u32)) as u64 * 16777619);
    }}
    return x;
}}

/// A result's line code: 0 ok, 1 InvalidInput, 2 another error.
fn codeOf(r: Result<void, AsyncError>) -> u64 => match (r) {{
    Ok() => 0,
    Err(AsyncError.Io(IoError.InvalidInput)) => 1,
    Err(_) => 2,
}};

/// The file: SIZE bytes, byte i being (7 i + 3) mod 251.
fn writeFile(path: StringView) -> Result<void, IoError> {{
    var file = File.create(path)?;
    var chunk = [0u8; 1000];
    var i: u64 = 0;
    while (i < {SIZE}) {{
        let n: u64 = if ({SIZE} - i < 1000) {SIZE} - i else 1000;
        for (k in 0..n) {{
            chunk[k as usize] = truncate<u8>((7 * (i + k) + 3) % 251);
        }}
        file.write(chunk[0..n as usize])?;
        i += n;
    }}
    return Ok();
}}

/// Reads until the peer shuts its side down, slowly: the count * 2^32 + the bytes' FNV-1a.
async fn readToEnd(stream: borrow AsyncTcpStream) -> Result<u64, AsyncError> {{
    var h: u32 = 2166136261;
    var got: u64 = 0;
    var buffer = [0u8; 1000];
    loop {{
        let n = await stream.read(mut buffer[..])?;
        if (n == 0) {{
            return Ok(got * 4294967296 + h as u64);
        }}
        let read = buffer[0..n];
        h = fnv(h, read);
        got += n as u64;
        if (got % 8 == 0) {{
            await Timer.sleep(1)?;
        }}
    }}
}}

fn show(code: u64, received: u64) {{
    Console.write(if (code == 0) "ok" else if (code == 1) "InvalidInput" else "another error");
    Console.write(" ");
    Console.write(received / 4294967296);
    Console.write(" ");
    Console.writeLine(received % 4294967296);
}}

/// A connected pair with small buffers: the client sends, the server reads.
async fn pair(
    listener: borrow AsyncTcpListener,
    port: u16,
) -> Result<AsyncTcpStream, AsyncError> {{
    let client = await AsyncTcpStream.connect("127.0.0.1", port)?;
    done(client.setSendBuffer(4096))?;
    return Ok(client);
}}

/// sendFileAll of `length` bytes from `offset`, then the client's side shut down: the result's code, and what the peer
/// read in `received`.
async fn line(
    listener: borrow AsyncTcpListener,
    port: u16,
    file: borrow File,
    offset: u64,
    length: u64,
    received: borrow mut u64,
) -> Result<u64, AsyncError> {{
    let client = await pair(listener, port)?;
    let server = await listener.accept()?;
    done(server.setRecvBuffer(4096))?;
    var result: Result<void, AsyncError> = Ok();
    var got: u64 = 0;
    await Async.all(
        async () => {{
            result = await client.sendFileAll(file, offset, length);
            done(client.shutdownWrite())?;
            return Ok();
        }},
        async () => {{
            got = await readToEnd(borrow server)?;
            return Ok();
        }},
    )?;
    received = got;
    return Ok(codeOf(result));
}}

/// One sendFile step of the whole file: 1 if it sent between 1 and every byte and the peer read exactly those.
async fn step(listener: borrow AsyncTcpListener, port: u16, file: borrow File) -> Result<u64, AsyncError> {{
    let client = await pair(listener, port)?;
    let server = await listener.accept()?;
    let sent = await client.sendFile(file, 0, {SIZE})?;
    done(client.shutdownWrite())?;
    if (sent == 0 || sent > {SIZE}) {{
        return Ok(9);
    }}
    let received = await readToEnd(borrow server)?;
    var whole = Vector<u8>.create();
    for (i in 0..sent) {{
        match (whole.push(truncate<u8>((7 * i + 3) % 251))) {{
            Ok() => {{}}
            Err(_) => {{ return Ok(7); }}
        }}
    }}
    let first = whole.view();
    return Ok(if (received == sent * 4294967296 + fnv(2166136261, first) as u64) 1 else 8);
}}

/// The whole file on two streams at once.
async fn twice(
    listener: borrow AsyncTcpListener,
    port: u16,
    file: borrow File,
    gotA: borrow mut u64,
    gotB: borrow mut u64,
) -> Result<void, AsyncError> {{
    let a = await pair(listener, port)?;
    let ra = await listener.accept()?;
    let b = await pair(listener, port)?;
    let rb = await listener.accept()?;
    var first: u64 = 0;
    var second: u64 = 0;
    await Async.all(
        async () => {{
            await Async.all(
                async () => {{
                    await a.sendFileAll(file, 0, {SIZE})?;
                    done(a.shutdownWrite())?;
                    return Ok();
                }},
                async () => {{
                    await b.sendFileAll(file, 0, {SIZE})?;
                    done(b.shutdownWrite())?;
                    return Ok();
                }},
            )?;
            return Ok();
        }},
        async () => {{
            await Async.all(
                async () => {{
                    first = await readToEnd(borrow ra)?;
                    return Ok();
                }},
                async () => {{
                    second = await readToEnd(borrow rb)?;
                    return Ok();
                }},
            )?;
            return Ok();
        }},
    )?;
    gotA = first;
    gotB = second;
    return Ok();
}}

/// Every case: two words a sendFileAll line (its code, what the peer read), then one step's check, the step at the end,
/// and the two streams'.
async fn run(file: borrow File) -> Result<[u64; {2 * n + 4}], AsyncError> {{
    var out = [0u64; {2 * n + 4}];
    let listener = io(AsyncTcpListener.bind("127.0.0.1", 0))?;
    let port = io(listener.port())?;
{calls}
    out[{2 * n}] = await step(borrow listener, port, file)?;
    {{
        let client = await pair(borrow listener, port)?;
        let server = await listener.accept()?;
        out[{2 * n + 1}] = await client.sendFile(file, {SIZE}, 5)?;
    }}
    await twice(borrow listener, port, file, mut out[{2 * n + 2}], mut out[{2 * n + 3}])?;
    return Ok(out);
}}

fn main() {{
    let root = Directory.temporary()!;
    var path = String.create();
    path.append(root.view())!;
    path.append("/sent")!;
    writeFile(path.view())!;
    {{
        // Closed at the block's end: Windows cannot remove an open file.
        var file = File.open(path.view())!;
        match (Async.run(run(borrow file))) {{
            Ok(out) => {{
                for (k in 0..{n}usize) {{
                    show(out[2 * k], out[2 * k + 1]);
                }}
                Console.writeLine(out[{2 * n}]);
                Console.writeLine(out[{2 * n + 1}]);
                show(0, out[{2 * n + 2}]);
                show(0, out[{2 * n + 3}]);
            }}
            Err(AsyncError.Io(e)) => {{ Console.writeLine(e.message()); }}
            Err(_) => {{ Console.writeLine("failed"); }}
        }}
        var first = [0u8; 5];
        let got = file.read(mut first[..])!;
        Console.write("position");
        for (k in 0..got) {{
            Console.write(" ");
            Console.write(first[k]);
        }}
        Console.writeLine("");
    }}
    File.remove(path.view())!;
    Directory.remove(root.view())!;
}}
{chr(10).join("// expect-stdout: " + e for e in expected)}
"""
    path = os.path.join(ROOT, "tests", "reference", "tests", "corpus", "run-pass", "async-send-file.cee")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(source)
    ceesafec = os.environ.get("CEESAFEC", os.path.join(ROOT, "out", "ceesafec"))
    subprocess.run([ceesafec, "fmt", path], check=True)
    print(f"gen_sendfile_cases: wrote {path} ({len(expected)} lines)")


if __name__ == "__main__":
    main()
