#!/usr/bin/env python3
"""Writes tests/reference/tests/corpus/run-pass/sort-patterns.cee: lib/core's sortBy (type-system.md §36.4, ADR 0057)
on every kind of input, against Python's `sorted` as the oracle.

For each pattern (random, ascending, descending, all equal, 16 distinct values, an ascending run with a smaller last
element, organ pipe, descending with duplicates, sawtooth, two values) and each length (0 to 700, around the
insertion-sort threshold of 16), the program builds the keys from the same 64-bit LCG as this file, and prints:

1. the FNV-1a of the keys sorted ascending, and of the keys sorted descending (a reversed comparator);
2. whether a sort of (key, original index) entries by key alone left the keys in the same order and the indices a
   permutation (sortBy is not stable, so the indices' order among equal keys is not checked).

Then, per pattern, 300 keys sorted first with a comparator that answers at random (an inconsistent order), then
properly: the hash must be the oracle's, so the inconsistent sort left a permutation (§36.4).

usage: python3 tools/oracles/gen_sort_cases.py   (formats with $CEESAFEC, default out/ceesafec)
"""

import os
import subprocess

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))
MASK = (1 << 64) - 1
PATTERNS = 10
SIZES = [0, 1, 2, 3, 15, 16, 17, 18, 33, 100, 700]
CHAOS_SIZE = 300


def fnv_word(h, value):
    for b in value.to_bytes(8, "little"):
        h = ((h ^ b) * 0x100000001B3) & MASK
    return h


def fnv(values):
    h = 0xCBF29CE484222325
    for v in values:
        h = fnv_word(h, v)
    return h


def keys(pattern, n):
    state = 7 + pattern
    out = []
    for i in range(n):
        state = (state * 6364136223846793005 + 1442695040888963407) & MASK
        r = state >> 33
        out.append([r, i, n - i, 7, r % 16, 0 if i == n - 1 else i + 1, i if i < n // 2 else n - i, (n - i) // 2,
                    i % 64, r % 2][pattern])
    return out


def main():
    expected = []
    calls = []
    for pattern in range(PATTERNS):
        for n in SIZES:
            k = keys(pattern, n)
            expected.append(f"{fnv(sorted(k))} {fnv(sorted(k, reverse=True))} true")
            calls.append(f"    case({pattern}, {n});")
    for pattern in range(PATTERNS):
        expected.append(str(fnv(sorted(keys(pattern, CHAOS_SIZE)))))
        calls.append(f"    chaos({pattern}, {CHAOS_SIZE});")
    nl = chr(10)
    source = f"""// GENERATED by tools/oracles/gen_sort_cases.py: edit that, not this file.
// lib/core's sortBy (type-system.md §36.4, ADR 0057) on {PATTERNS} input patterns and {len(SIZES)} lengths, each expected
// line from Python's sorted: the FNV-1a of the keys sorted ascending and descending, then whether (key, index) entries
// sorted by key have the same keys and a permutation of the indices; last, an inconsistent comparator's result sorted
// again, which must hash as the input sorted (a permutation, §36.4).

struct Entry {{
    key: u64;
    at: u64;
}}

fn fnv(h: u64, value: u64) -> u64 {{
    var x = h;
    for (k in 0..8u64) {{
        x = (x ^ ((value >> (8 * k)) & 0xFF)).wrappingMul(0x100000001B3);
    }}
    return x;
}}

fn hash(v: Slice<u64>) -> u64 {{
    var h: u64 = 0xCBF29CE484222325;
    for (i in 0..v.length) {{
        h = fnv(h, v[i]);
    }}
    return h;
}}

fn next(state: borrow mut u64) -> u64 {{
    state = state.wrappingMul(6364136223846793005).wrappingAdd(1442695040888963407);
    return state >> 33;
}}

fn key(pattern: u64, i: u64, n: u64, r: u64) -> u64 {{
    if (pattern == 0) {{ return r; }}
    if (pattern == 1) {{ return i; }}
    if (pattern == 2) {{ return n - i; }}
    if (pattern == 3) {{ return 7; }}
    if (pattern == 4) {{ return r % 16; }}
    if (pattern == 5) {{ return if (i == n - 1) 0 else i + 1; }}
    if (pattern == 6) {{ return if (i < n / 2) i else n - i; }}
    if (pattern == 7) {{ return (n - i) / 2; }}
    if (pattern == 8) {{ return i % 64; }}
    return r % 2;
}}

fn make(pattern: u64, n: u64) -> Vector<u64> {{
    var s: u64 = 7 + pattern;
    var keys = Vector<u64>.create();
    for (i in 0..n) {{
        keys.push(key(pattern, i, n, next(mut s)))!;
    }}
    return keys;
}}

fn case(pattern: u64, n: u64) {{
    var up = make(pattern, n);
    var down = make(pattern, n);
    var entries = Vector<Entry>.create();
    for (i in 0..up.length) {{
        entries.push(Entry {{ key: up[i], at: i as u64 }})!;
    }}
    up.sortBy((a, b) => if (a < b) -1 else if (a > b) 1 else 0);
    down.sortBy((a, b) => if (a > b) -1 else if (a < b) 1 else 0);
    entries.sortBy((a, b) => if (a.key < b.key) -1 else if (a.key > b.key) 1 else 0);
    var seen = Vector<bool>.create();
    for (i in 0..entries.length) {{
        seen.push(false)!;
    }}
    var same = true;
    for (i in 0..entries.length) {{
        let at = truncate<usize>(entries[i].at);
        if (entries[i].key != up[i] || at >= seen.length || seen[at]) {{
            same = false;
        }} else {{
            seen[at] = true;
        }}
    }}
    Console.write(hash(up));
    Console.write(" ");
    Console.write(hash(down));
    Console.write(" ");
    Console.writeLine(same);
}}

fn chaos(pattern: u64, n: u64) {{
    var keys = make(pattern, n);
    var t: u64 = 12345 + pattern;
    keys.sortBy((a, b) => truncate<i32>(next(mut t) % 3) - 1);
    keys.sortBy((a, b) => if (a < b) -1 else if (a > b) 1 else 0);
    Console.writeLine(hash(keys));
}}

fn main() {{
{nl.join(calls)}
}}
{nl.join("// expect-stdout: " + e for e in expected)}
"""
    path = os.path.join(ROOT, "tests", "reference", "tests", "corpus", "run-pass", "sort-patterns.cee")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(source)
    ceesafec = os.environ.get("CEESAFEC", os.path.join(ROOT, "out", "ceesafec"))
    subprocess.run([ceesafec, "fmt", path], check=True)
    print(f"gen_sort_cases: wrote {path} ({len(expected)} lines)")


if __name__ == "__main__":
    main()
