#!/usr/bin/env python3
"""Writes tests/reference/tests/corpus/run-pass/sort-stable-patterns.cee: lib/core's sortStableBy (type-system.md §36.4,
ADR 0225) on every kind of input, against Python's `sorted`, which is stable, as the oracle.

The inputs are gen_sort_cases.py's patterns, at lengths around the insertion blocks of 20 and the merges that join
them (0 to 1000). Each element is (key, original index). For each pattern and length the program prints:

1. the FNV-1a of the original indices after a sort by key ascending, then after a sort by key descending (a
   reversed comparator), each of a fresh copy: a stable sort keeps the indices of equal keys ascending, so the hash
   fixes the whole order;
2. the same for a sort by the key modulo 4, where most keys are equal.

Then, per pattern, 300 elements sorted first with a comparator that answers at random (an inconsistent order), then
by key: the keys must hash as the input's sorted keys, so the inconsistent sort left a permutation (§36.4).

usage: python3 tools/oracles/gen_stable_sort_cases.py   (formats with $CEESAFEC, default out/ceesafec)
"""

import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_sort_cases import CHAOS_SIZE, PATTERNS, ROOT, fnv, keys  # noqa: E402

SIZES = [0, 1, 2, 19, 20, 21, 39, 40, 41, 80, 81, 100, 333, 1000]


def order(k, key, reverse):
    """The original indices of `k` after a stable sort by `key` (descending when `reverse`, still stable)."""
    return [i for i, _ in sorted(enumerate(k), key=lambda e: key(e[1]), reverse=reverse)]


def main():
    expected = []
    calls = []
    for pattern in range(PATTERNS):
        for n in SIZES:
            k = keys(pattern, n)
            # sorted(reverse=True) is stable too: equal keys keep their original order.
            line = [fnv(order(k, lambda x: x, False)), fnv(order(k, lambda x: x, True)),
                    fnv(order(k, lambda x: x % 4, False)), fnv(order(k, lambda x: x % 4, True))]
            expected.append(" ".join(str(h) for h in line))
            calls.append(f"    case({pattern}, {n});")
    for pattern in range(PATTERNS):
        expected.append(str(fnv(sorted(keys(pattern, CHAOS_SIZE)))))
        calls.append(f"    chaos({pattern}, {CHAOS_SIZE});")
    nl = chr(10)
    source = f"""// GENERATED by tools/oracles/gen_stable_sort_cases.py: edit that, not this file.
// lib/core's sortStableBy (type-system.md §36.4, ADR 0225) on {PATTERNS} input patterns and {len(SIZES)} lengths, each
// expected line from Python's sorted, which is stable: the FNV-1a of the original indices after sorts by key ascending
// and descending, and by the key modulo 4 ascending and descending; last, an inconsistent comparator's result sorted
// again by key, which must hash as the input's keys sorted (a permutation, §36.4).

struct Entry {{
    key: u64;
    at: u64;
}}

fn fnv(h: u64, value: u64) -> u64 {{
    var x = h;
    for (k in 0..8u64) {{
        x = (x ^ ((value >> (8 * k)) & 0xFF)).wrappingMul(0x100000001B3);
    }}
    return x;
}}

fn hashPlaces(v: Slice<Entry>) -> u64 {{
    var h: u64 = 0xCBF29CE484222325;
    for (i in 0..v.length) {{
        h = fnv(h, v[i].at);
    }}
    return h;
}}

fn hashKeys(v: Slice<Entry>) -> u64 {{
    var h: u64 = 0xCBF29CE484222325;
    for (i in 0..v.length) {{
        h = fnv(h, v[i].key);
    }}
    return h;
}}

fn next(state: borrow mut u64) -> u64 {{
    state = state.wrappingMul(6364136223846793005).wrappingAdd(1442695040888963407);
    return state >> 33;
}}

fn key(pattern: u64, i: u64, n: u64, r: u64) -> u64 {{
    if (pattern == 0) {{ return r; }}
    if (pattern == 1) {{ return i; }}
    if (pattern == 2) {{ return n - i; }}
    if (pattern == 3) {{ return 7; }}
    if (pattern == 4) {{ return r % 16; }}
    if (pattern == 5) {{ return if (i == n - 1) 0 else i + 1; }}
    if (pattern == 6) {{ return if (i < n / 2) i else n - i; }}
    if (pattern == 7) {{ return (n - i) / 2; }}
    if (pattern == 8) {{ return i % 64; }}
    return r % 2;
}}

fn make(pattern: u64, n: u64) -> Vector<Entry> {{
    var s: u64 = 7 + pattern;
    var entries = Vector<Entry>.create();
    for (i in 0..n) {{
        entries.push(Entry {{ key: key(pattern, i, n, next(mut s)), at: i }})!;
    }}
    return entries;
}}

fn compare(a: u64, b: u64) -> i32 => if (a < b) -1 else if (a > b) 1 else 0;

fn case(pattern: u64, n: u64) {{
    var up = make(pattern, n);
    up.sortStableBy((a, b) => compare(a.key, b.key));
    var down = make(pattern, n);
    down.sortStableBy((a, b) => compare(b.key, a.key));
    var few = make(pattern, n);
    few.sortStableBy((a, b) => compare(a.key % 4, b.key % 4));
    var fewDown = make(pattern, n);
    fewDown[..].sortStableBy((a, b) => compare(b.key % 4, a.key % 4));
    Console.write(hashPlaces(up));
    Console.write(" ");
    Console.write(hashPlaces(down));
    Console.write(" ");
    Console.write(hashPlaces(few));
    Console.write(" ");
    Console.writeLine(hashPlaces(fewDown));
}}

fn chaos(pattern: u64, n: u64) {{
    var entries = make(pattern, n);
    var t: u64 = 12345 + pattern;
    entries.sortStableBy((a, b) => truncate<i32>(next(mut t) % 3) - 1);
    entries.sortStableBy((a, b) => compare(a.key, b.key));
    Console.writeLine(hashKeys(entries));
}}

fn main() {{
{nl.join(calls)}
}}
{nl.join("// expect-stdout: " + e for e in expected)}
"""
    path = os.path.join(ROOT, "tests", "reference", "tests", "corpus", "run-pass", "sort-stable-patterns.cee")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(source)
    ceesafec = os.environ.get("CEESAFEC", os.path.join(ROOT, "out", "ceesafec"))
    subprocess.run([ceesafec, "fmt", path], check=True)
    print(f"gen_stable_sort_cases: wrote {path} ({len(expected)} lines)")


if __name__ == "__main__":
    main()
