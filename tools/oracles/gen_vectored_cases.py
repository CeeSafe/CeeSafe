#!/usr/bin/env python3
"""Writes tests/reference/tests/corpus/run-pass/async-tcp-vectored.cee: lib/std's vectored sends (ADR 0045) on a list of
part layouts, with each expected line computed here, the oracle:

- for each layout, the bytes the peer must receive: the parts in order, byte i of the whole being (7 * i + case) % 251;
  the line is "<total> <FNV-1a 32 of those bytes>", once through writeAllVectored (the sender's buffers small and the
  reader slow, so the sends are partial across part boundaries) and once through one writeVectored step, whose count
  the peer then reads ("<count is between 1 and total> <FNV-1a of the first count bytes>": 1 for yes);
- IoParts.after(skip) for each skip: the remaining part lengths;
- IoParts.then on eight parts: null.

usage: python3 tools/oracles/gen_vectored_cases.py   (formats with $CEESAFEC, default out/ceesafec)
"""

import os
import subprocess

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))

# Part layouts sent through a socket.
LAYOUTS = [
    [0],
    [1],
    [5, 0, 7],
    [0, 0, 3],
    [1, 2, 3, 4, 5, 6, 7, 8],
    [70000, 1, 130000],
    [3, 100000, 0, 2],
]

# (layout, skips) for IoParts.after.
AFTER = [
    ([5, 0, 7], [0, 3, 5, 6, 12, 13]),
    ([1, 2, 3, 4, 5, 6, 7, 8], [0, 1, 10, 35, 36]),
]


def content(case, total):
    return bytes((7 * i + case) % 251 for i in range(total))


def fnv(data):
    h = 2166136261
    for b in data:
        h = ((h ^ b) * 16777619) & 0xFFFFFFFF
    return h


def after(sizes, skip):
    """The part lengths after the first `skip` bytes, as IoParts.after makes them (ADR 0045 §3.1)."""
    k, left = 0, skip
    while k < len(sizes) and left >= sizes[k]:
        left -= sizes[k]
        k += 1
    if k == len(sizes):
        return []
    return [sizes[k] - left] + sizes[k + 1:]


def layout_literal(sizes):
    return "[" + ", ".join(f"{s}usize" for s in sizes) + "]"


def main():
    expected = []
    for case, sizes in enumerate(LAYOUTS):
        total = sum(sizes)
        data = content(case, total)
        expected.append(f"{total} {fnv(data)}")
    for case, sizes in enumerate(LAYOUTS):
        total = sum(sizes)
        # One step sends at least one byte of a non-empty layout, the whole of a small one; the peer reads that many.
        expected.append("1" if total > 0 else "0")
    for sizes, skips in AFTER:
        for skip in skips:
            expected.append(",".join(str(n) for n in after(sizes, skip)) or "none")
    expected.append("full")

    calls = []
    for case, sizes in enumerate(LAYOUTS):
        calls.append(f"    let all{case} = {layout_literal(sizes)};")
        calls.append(f"    out[{case}] = await sendAll(borrow listener, port, {case}, all{case}[..])?;")
    for case, sizes in enumerate(LAYOUTS):
        calls.append(f"    let one{case} = {layout_literal(sizes)};")
        calls.append(f"    out[{len(LAYOUTS) + case}] = await sendOnce(borrow listener, port, {case}, one{case}[..])?;")
    afters = []
    for n, (sizes, skips) in enumerate(AFTER):
        afters.append(f"    let sizes{n} = {layout_literal(sizes)};")
        for skip in skips:
            afters.append(f"    showAfter(sizes{n}[..], {skip});")

    source = f"""// GENERATED by tools/oracles/gen_vectored_cases.py: edit that, not this file.
// lib/std's vectored sends (ADR 0045): IoParts over one buffer, sent with writeAllVectored to a slow reader through
// small socket buffers (so sends stop inside parts), and with one writeVectored step; IoParts.after and a ninth part.
// Each expected line is the generator's (the bytes' total and FNV-1a, computed in Python).

fn io<T>(r: Result<T, IoError>) -> Result<T, AsyncError> => match (r) {{
    Ok(v) => Ok(v),
    Err(e) => Err(AsyncError.Io(e)),
}};

fn done(r: Result<void, IoError>) -> Result<void, AsyncError> => match (r) {{
    Ok() => Ok(),
    Err(e) => Err(AsyncError.Io(e)),
}};

fn fnv(h: u32, bytes: Slice<u8>) -> u32 {{
    var x = h;
    for (b in bytes) {{
        x = truncate<u32>((x ^ (b as u32)) as u64 * 16777619);
    }}
    return x;
}}

/// One more part, unless the parts are full.
fn grow<region r>(parts: IoParts<r>, part: Slice<r, u8>, more: bool) -> IoParts<r> {{
    if (!more) {{
        return parts;
    }}
    return match (parts.then(part)) {{
        Some(p) => p,
        null => parts,
    }};
}}

/// The parts of `all` whose lengths are `sizes` (at most eight).
fn partsOf<region r>(all: Slice<r, u8>, sizes: Slice<usize>) -> IoParts<r> {{
    var bounds = [0usize; 9];
    for (k in 0..sizes.length) {{
        bounds[k + 1] = bounds[k] + sizes[k];
    }}
    let n = sizes.length;
    let p1 = IoParts.of(all[bounds[0]..bounds[1]]);
    let p2 = grow(p1, all[bounds[1]..bounds[if (n > 1) 2 else 1]], n > 1);
    let p3 = grow(p2, all[bounds[2]..bounds[if (n > 2) 3 else 2]], n > 2);
    let p4 = grow(p3, all[bounds[3]..bounds[if (n > 3) 4 else 3]], n > 3);
    let p5 = grow(p4, all[bounds[4]..bounds[if (n > 4) 5 else 4]], n > 4);
    let p6 = grow(p5, all[bounds[5]..bounds[if (n > 5) 6 else 5]], n > 5);
    let p7 = grow(p6, all[bounds[6]..bounds[if (n > 6) 7 else 6]], n > 6);
    return grow(p7, all[bounds[7]..bounds[if (n > 7) 8 else 7]], n > 7);
}}

/// The case's bytes: byte i is (7 i + case) mod 251.
fn content(case: u32, total: usize) -> Result<Vector<u8>, AllocError> {{
    var v = Vector<u8>.create();
    for (i in 0..total) {{
        v.push(truncate<u8>((7 * i as u64 + case as u64) % 251))?;
    }}
    return Ok(v);
}}

fn total(sizes: Slice<usize>) -> usize {{
    var n: usize = 0;
    for (s in sizes) {{
        n += s;
    }}
    return n;
}}

/// Reads `want` bytes slowly (small reads with a pause), and their FNV-1a.
async fn readSlowly(stream: borrow AsyncTcpStream, want: usize) -> Result<u32, AsyncError> {{
    var h: u32 = 2166136261;
    var got: usize = 0;
    var buffer = [0u8; 1000];
    while (got < want) {{
        let n = await stream.read(mut buffer[..])?;
        if (n == 0) {{
            return Err(AsyncError.TimedOut); // the sender stopped early
        }}
        let read = buffer[0..n];
        h = fnv(h, read);
        got += n;
        if (got % 8 == 0) {{
            await Timer.sleep(1)?;
        }}
    }}
    return Ok(h);
}}

/// Sends the case through writeAllVectored; the line's number is total * 2^32 + FNV-1a as the peer read it.
async fn sendAll(listener: borrow AsyncTcpListener, port: u16, case: u32, sizes: Slice<usize>) -> Result<u64, AsyncError> {{
    let n = total(sizes);
    let bytes = match (content(case, n)) {{
        Ok(v) => v,
        Err(_) => {{ return Err(AsyncError.Cancelled); }},
    }};
    let client = await AsyncTcpStream.connect("127.0.0.1", port)?;
    let server = await listener.accept()?;
    done(client.setSendBuffer(4096))?;
    done(server.setRecvBuffer(4096))?;
    var h: u32 = 0;
    await Async.all(
        async () => {{
            let all = bytes.view();
            let parts = partsOf(all, sizes);
            await client.writeAllVectored(borrow parts)?;
            return Ok();
        }},
        async () => {{
            h = await readSlowly(borrow server, n)?;
            return Ok();
        }},
    )?;
    return Ok((n as u64) * 4294967296 + h as u64);
}}

/// One writeVectored step: 1 if it sent between 1 and every byte (0 for an empty layout, which sends nothing) and the
/// peer read exactly those bytes.
async fn sendOnce(listener: borrow AsyncTcpListener, port: u16, case: u32, sizes: Slice<usize>) -> Result<u64, AsyncError> {{
    let n = total(sizes);
    let bytes = match (content(case, n)) {{
        Ok(v) => v,
        Err(_) => {{ return Err(AsyncError.Cancelled); }},
    }};
    let client = await AsyncTcpStream.connect("127.0.0.1", port)?;
    let server = await listener.accept()?;
    let all = bytes.view();
    let parts = partsOf(all, sizes);
    let sent = await client.writeVectored(borrow parts)?;
    if (n == 0) {{
        return Ok(if (sent == 0) 0 else 9);
    }}
    if (sent == 0 || sent > n) {{
        return Ok(9);
    }}
    let h = await readSlowly(borrow server, sent)?;
    let first = all[0..sent];
    return Ok(if (h == fnv(2166136261, first)) 1 else 8);
}}

async fn run() -> Result<[u64; {2 * len(LAYOUTS)}], AsyncError> {{
    var out = [0u64; {2 * len(LAYOUTS)}];
    let listener = io(AsyncTcpListener.bind("127.0.0.1", 0))?;
    let port = io(listener.port())?;
{chr(10).join(calls)}
    return Ok(out);
}}

fn showAfter(sizes: Slice<usize>, skip: usize) {{
    let n = total(sizes);
    let bytes = match (content(0, n)) {{
        Ok(v) => v,
        Err(_) => {{ return; }},
    }};
    let all = bytes.view();
    let parts = partsOf(all, sizes);
    let rest = parts.after(skip);
    if (rest.count() == 0) {{
        Console.writeLine("none");
        return;
    }}
    for (i in 0..rest.count()) {{
        if (i > 0) {{
            Console.write(",");
        }}
        Console.write(rest.part(i).length);
    }}
    Console.writeLine("");
}}

fn main() {{
    match (Async.run(run())) {{
        Ok(lines) => {{
            for (k in 0..lines.length) {{
                let v = lines[k];
                if (k < {len(LAYOUTS)}) {{
                    Console.write(v / 4294967296);
                    Console.write(" ");
                    Console.writeLine(v % 4294967296);
                }} else {{
                    Console.writeLine(v);
                }}
            }}
        }}
        Err(AsyncError.Io(e)) => {{ Console.writeLine(e.message()); }}
        Err(_) => {{ Console.writeLine("failed"); }}
    }}
{chr(10).join(afters)}
    let eight = [0u8; 8];
    let all = eight[..];
    let ones = [1usize; 8];
    let full = partsOf(all, ones[..]);
    Console.writeLine(if (full.then(all[0..1]) == null) "full" else "room");
}}
{chr(10).join("// expect-stdout: " + e for e in expected)}
"""
    path = os.path.join(ROOT, "tests", "reference", "tests", "corpus", "run-pass", "async-tcp-vectored.cee")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(source)
    ceesafec = os.environ.get("CEESAFEC", os.path.join(ROOT, "out", "ceesafec"))
    subprocess.run([ceesafec, "fmt", path], check=True)
    print(f"gen_vectored_cases: wrote {path} ({len(expected)} lines)")


if __name__ == "__main__":
    main()
